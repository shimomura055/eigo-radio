# -*- coding: utf-8 -*-
import json, os
ROOT = os.path.dirname(os.path.abspath(__file__)); OUT = f"{ROOT}/er057_output/coffee_comment4_trial_01"
rows = json.load(open(f"{OUT}/metrics.json", encoding="utf-8"))
# Sonnet読解所見(非断定): F終盤感/L聞き終え/B英語橋渡し/N不自然さなし/R本文再説明なし  (○/△/×)
READ = {
 ("C0",1): ("×","×","○","○","○","終盤感・聞き終えを示す語なし。『続いて』の事務的つなぎ"),
 ("C0",2): ("×","△","○","○","○","『関わっていました』で総括するが終盤感は無い"),
 ("C0",3): ("×","×","×","○","○","『英語』の語が無く、英語要約への橋渡しにならない"),
 ("C1",1): ("○","○","○","○","△","『最後に』『ここまで』あり。回収2文でやや長い"),
 ("C1",2): ("△","○","○","○","○","『ここまで』『結びのまとめ』。『最後に』等の終盤語は無く終盤感は弱め"),
 ("C1",3): ("○","○","○","○","△","『すべて聞き終えました』『最後に』と3軸が最も明確。回収2文で再説明気味"),
 ("C2",1): ("○","○","○","○","○","『聞き終えて、番組も終盤に入りました』。口語的で自然"),
 ("C2",2): ("○","○","○","△","○","『伝わるまでの時間』が不自然。『終わりに近づいて』は番組締めの挨拶寄り"),
 ("C2",3): ("○","○","○","△","○","『お聞きください』がやや硬い"),
 ("C3",1): ("×","△","○","×","△","『ここまでの内容を続いて英語のまとめで振り返ります』が文のねじれで不自然"),
 ("C3",2): ("×","×","○","○","○","橋渡しは明確だが終盤感・聞き終え感なし"),
 ("C3",3): ("×","△","○","○","○","『ここからは』で区切りはあるが終盤感なし"),
 ("C4",1): ("×","×","○","△","○","問いかけ形で回収が弱く、本文の結論とずれる印象"),
 ("C4",2): ("×","○","○","○","○","『たどってきました』で聞き終え感。終盤感は無い"),
 ("C4",3): ("×","○","○","○","△","『ここまでの記事から』で聞き終え感。回収が長め"),
}
b = lambda x: "○" if x else "×"
L = ["| 候補 | run | 文字数 | 文数 | 決定論 F終盤語 | L聞き終え語 | B最終文に英語 | 禁止要素 | 読解 F | L | B | N不自然さなし | R再説明なし | 本文 | 読解メモ |", "|---|---|---|---|---|---|---|---|---|---|---|---|---|---|---|"]
for r in rows:
    d = r["det"]; k = (r["cand"], r["run"]); rd = READ[k]
    L.append(f"| {r['cand']} | {r['run']} | {d['chars']} | {d['sentences']} | {b(d['F終盤感'])} | {b(d['L聞き終え'])} | {b(d['B英語橋渡し'])} | {','.join(d['bad']) or 'なし'} | {rd[0]} | {rd[1]} | {rd[2]} | {rd[3]} | {rd[4]} | {r['text']} | {rd[5]} |")
tbl = "\n".join(L)
# 集計
S = ["| 候補 | 平均文字数 | 決定論F | 決定論L | 決定論B | 読解で3軸(F,L,B)全て○ | N△/×あり | R△あり |", "|---|---|---|---|---|---|---|---|"]
for c in ("C0","C1","C2","C3","C4"):
    rs = [r for r in rows if r["cand"] == c]
    f3 = sum(1 for r in rs if READ[(c, r["run"])][:3] == ("○","○","○"))
    S.append(f"| {c} | {sum(r['det']['chars'] for r in rs)/3:.0f} | {sum(r['det']['F終盤感'] for r in rs)}/3 | {sum(r['det']['L聞き終え'] for r in rs)}/3 | {sum(r['det']['B英語橋渡し'] for r in rs)}/3 | {f3}/3 | {sum(1 for r in rs if READ[(c,r['run'])][3] != '○')}/3 | {sum(1 for r in rs if READ[(c,r['run'])][4] != '○')}/3 |")
open(f"{OUT}/repro_table.md", "w", encoding="utf-8").write("## 再現性(3回x5候補)\n\n" + tbl + "\n\n## 集計\n\n" + "\n".join(S) + "\n")
print("\n".join(S))
